"""组合式题库：场景 × 行为 → 每种量表 100 题（题干不重复）。

做法：为每个维度写若干「行为句」，再与通用场景池组合成陈述句
（"在{场景}，{行为}。"），按维度均衡取样到 100 题。
每次作答从题库随机抽题，所以两次不会完全一样——这也是减少「记住上次答案」的标准做法。

全部为**原创条目**；PHQ-9 / GAD-7 / UCLA 的官方原题保留在 `OFFICIAL` 里，
选「官方题数」时用它并按原量表分级，选更多题则进入「扩展自评」（不套用官方分级）。
"""

from __future__ import annotations

import random

# ── 通用场景池 ───────────────────────────────────────────────
SCENES = [
    "在一群不太熟的人里", "在饭桌上", "在群里", "在周末", "在深夜",
    "在刚认识的人面前", "在需要做决定的时候", "在被点名的时候", "在别人求助的时候",
    "在话题冷下来的时候", "在计划被打乱的时候", "在被夸奖的时候", "在和人意见不同的时候",
    "在心里不舒服的时候", "在遇到新东西的时候", "在排队等候的时候", "在忙了一天之后",
    "在需要开口拒绝的时候",
]


def build(preds_by_dim, scenes=None, total=100, frame="{scene}，{pred}。"):
    """「场景 × 行为」组合成**恰好 total 题**，维度轮转保证均衡、题干去重。"""
    scenes = scenes or SCENES
    dims = list(preds_by_dim.items())
    # 每个维度各自把所有组合打散，然后按轮转一圈一圈地取，直到凑满 total
    pools = {}
    for dim, preds in dims:
        combos = [(scene, pred) for pred in preds for scene in scenes]
        rng = random.Random(f"{dim}-{len(preds)}-{total}")
        rng.shuffle(combos)
        pools[dim] = combos

    out = []
    seen = set()
    index = 0
    while len(out) < total and any(pools.values()):
        for dim, _ in dims:
            pool = pools[dim]
            while pool:
                scene, pred = pool.pop(0)
                text = frame.format(scene=scene, pred=pred)
                if text in seen:
                    continue
                seen.add(text)
                out.append({"text": text, "dim": dim, "reverse": False})
                break
            if len(out) >= total:
                break
        index += 1
        if index > total * 4:
            break
    return out[:total]


