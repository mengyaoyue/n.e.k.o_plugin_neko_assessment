def _items(dim, rows):
    return [{"text": text, "dim": dim, "reverse": bool(rev)} for text, rev in rows]


def _choice_items(rows):
    """rows: [(题干, [(选项文字, 维度键)])] → 强制选择题（选项带 weight=2）。"""
    out = []
    for text, options in rows:
        out.append({
            "text": text,
            "options": [{"label": label, "weights": {key: 2}} for label, key in options],
        })
    return out


